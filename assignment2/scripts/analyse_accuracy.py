#!/usr/bin/env python3
"""A2 Step 4 accuracy: every configuration on the 80 test (even) rows, against ACCURACY_LIMITS.md.

  python assignment2/scripts/analyse_accuracy.py

Sources (per-ticket answers):
  Llama alone   assignment2/results/step1_top_model_test_set/predictions.csv (re-run 18 Nov; identical to A1)
  Qwen, Gemma   step5/results/<model>/accuracy/predictions.csv, even rows only: A1 records reused (brief Step 4;
                same digest, prompt, Ollama version and machine, ACCURACY_LIMITS.md)
  Cascade A, B  assignment2/results/accuracy/cascade{A,B}/predictions.csv + api.log triage lines
Invalid answers and errors count as wrong. Writes assignment2/results/accuracy/summary.md and summary.json.
"""
import csv
import json
import math
import re
from collections import Counter
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATS = ["Credit reporting", "Debt collection", "Mortgage", "Credit card", "Bank account or service", "Consumer loan", "Money transfer or service"]
SHORT = ["CR", "DC", "Mtg", "CC", "Bank", "Loan", "MT"]
INV = "(invalid/error)"
TEST = {r["row"] for r in csv.DictReader(open(ROOT / "assignment2/data/test_set.csv", encoding="utf-8"))}
SOURCES = {
    "Llama alone": ROOT / "assignment2/results/step1_top_model_test_set/predictions.csv",
    "Qwen alone": ROOT / "step5/results/qwen3-4b/accuracy/predictions.csv",
    "Gemma alone": ROOT / "step5/results/gemma3-1b/accuracy/predictions.csv",
    "Cascade A": ROOT / "assignment2/results/accuracy/cascadeA/predictions.csv",
    "Cascade B": ROOT / "assignment2/results/accuracy/cascadeB/predictions.csv",
}


def load(path: Path) -> dict[str, dict]:
    rows = {r["row"]: r for r in csv.DictReader(open(path, encoding="utf-8")) if r["row"] in TEST}
    assert len(rows) == 80, f"{path}: {len(rows)} test rows"
    return rows


def main() -> int:
    ref = load(SOURCES["Llama alone"])
    # Limits from ACCURACY_LIMITS.md: overall floor = ref - 10 pts, category floor = ref - 15 pts; min correct = ceil.
    n_cat = Counter(r["golden"] for r in ref.values())
    ref_ok = {c: sum(r["correct"] == "True" for r in ref.values() if r["golden"] == c) for c in CATS}
    ref_all = sum(r["correct"] == "True" for r in ref.values())
    floor = {c: math.ceil((Fraction(ref_ok[c], n_cat[c]) - Fraction(15, 100)) * n_cat[c]) for c in CATS}
    floor_all = math.ceil((Fraction(ref_all, 80) - Fraction(10, 100)) * 80)

    out, lines = {}, ["# A2 accuracy on the 80 test rows (generated by assignment2/scripts/analyse_accuracy.py)", ""]
    lines += [f"Limits (from Llama alone, {ref_all}/80): overall >= {floor_all}/80; per category >= "
              + ", ".join(f"{s} {floor[c]}/{n_cat[c]}" for s, c in zip(SHORT, CATS)), ""]
    lines += ["| Configuration | Overall | " + " | ".join(f"{s} (>= {floor[c]}/{n_cat[c]})" for s, c in zip(SHORT, CATS)) + " | Passes |",
              "|---|---|" + "---|" * len(CATS) + "---|"]
    for name, path in SOURCES.items():
        rows = load(path)
        ok = sum(r["correct"] == "True" for r in rows.values())
        per = {c: sum(r["correct"] == "True" for r in rows.values() if r["golden"] == c) for c in CATS}
        fails = [s for s, c in zip(SHORT, CATS) if per[c] < floor[c]] + (["overall"] if ok < floor_all else [])
        cm = Counter((r["golden"], r["predicted"]) for r in rows.values())
        out[name] = {"correct": ok, "per_category": per, "fails": fails, "invalid": sum(r["predicted"] == INV for r in rows.values()),
                     "confusion": {g: {p: cm[(g, p)] for p in CATS + [INV]} for g in CATS}}
        lines.append(f"| {name} | {ok}/80 = {100 * ok / 80:.2f}% | " + " | ".join(
            f"{per[c]}/{n_cat[c]}{'' if per[c] >= floor[c] else ' ✗'}" for c in CATS) + f" | {'yes' if not fails else 'no: ' + ', '.join(fails)} |")

    lines += ["", "## Cascade: escalated vs accepted tickets (test set, from the triage log lines)", "",
              "| Setting | Escalated | of which invalid Gemma answer / category | Accuracy escalated | Accuracy accepted | Accepted and wrong |",
              "|---|---|---|---|---|---|"]
    for name, key in (("Cascade A", "cascadeA"), ("Cascade B", "cascadeB")):
        log = (ROOT / f"assignment2/results/accuracy/{key}/api.log").read_text(encoding="utf-8", errors="replace")
        tri = {}
        for m in re.finditer(r"triage (\{.*\})", log):
            t = json.loads(m.group(1))
            if t["request_id"].startswith(f"acc-a2-{key}-"):
                tri[t["request_id"].rsplit("-", 1)[1]] = t
        rows = load(SOURCES[name])
        esc = [r for k, r in rows.items() if tri[k]["escalated"]]
        acc = [r for k, r in rows.items() if not tri[k]["escalated"]]
        inv = sum(1 for k in rows if tri[k]["reason"] == "invalid")
        cat = sum(1 for k in rows if tri[k]["reason"] == "category")
        e_ok, a_ok = sum(r["correct"] == "True" for r in esc), sum(r["correct"] == "True" for r in acc)
        out[name] |= {"escalated": len(esc), "esc_invalid": inv, "esc_category": cat, "esc_correct": e_ok, "acc_n": len(acc), "acc_correct": a_ok,
                      "accepted_wrong_true_categories": dict(Counter(r["golden"] for r in acc if r["correct"] != "True"))}
        lines.append(f"| {name} | {len(esc)}/80 = {100 * len(esc) / 80:.1f}% | {inv} / {cat} | {e_ok}/{len(esc)} = {100 * e_ok / len(esc):.1f}% | "
                     f"{a_ok}/{len(acc)} = {100 * a_ok / len(acc):.1f}% | {len(acc) - a_ok}: " +
                     ", ".join(f"{k} {v}" for k, v in out[name]["accepted_wrong_true_categories"].items()) + " |")
    lines += ["", "Small categories: Mortgage (7), Credit card (6) and Consumer loan (8) have fewer than 10 test tickets; one ticket",
              "moves them 12.5-16.7 points, and Credit card's floor (6/6) fails on a single error.",
              "Qwen and Gemma: Assignment 1 per-ticket records reused, even rows only (unchanged digest, prompt, Ollama, machine)."]
    (ROOT / "assignment2/results/accuracy/summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (ROOT / "assignment2/results/accuracy/summary.json").write_text(
        json.dumps({"floor_overall": floor_all, "floor": floor, "n": dict(n_cat), "configs": out}, indent=2), encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
